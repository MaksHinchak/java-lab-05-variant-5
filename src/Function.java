import java.util.Objects; // Допоміжний метод формує хеш-код за класом і параметрами.
// class описує тип об’єктів; new створює конкретний об’єкт і викликає його конструктор. public робить клас
// доступним ззовні; final у заголовку класу, якщо він є, забороняє створювати підкласи, але сам по собі не робить
// поля незмінними.
// Об’єкт самого abstract-класу створити не можна. Він зберігає спільні півосі чи механізм роботи, а відсутні
// реалізації методів надають підкласи; перевірка цього обов’язку відбувається під час компіляції.
public abstract class Function { // Абстрактна функція не створюється без конкретного підкласу.
    // protected дає доступ підкласам і класам того самого пакета. final фіксує значення після конструктора: півосі
    // не можна випадково змінити між обчисленням, порівнянням і хешуванням.
    protected final double a; // Додатний масштаб уздовж осі x доступний підкласам.
    protected final double b; // Додатний масштаб уздовж осі y.
    protected Function(double a, double b) { // Конструктор базової частини викликається з підкласу через super.
        // Double.isFinite(...) повертає true лише для звичайного скінченного числа; ! заперечує результат. double
        // може містити NaN («не число») і ±Infinity, тому успішний parseDouble ще не гарантує придатність числа
        // для формули. У Python аналог — math.isfinite(x); ця перевірка не перевіряє точність округлення.
        // throw — аналог raise у Python: негайно припиняємо звичайний хід методу й передаємо об’єкт помилки
        // найближчому відповідному catch. new створює виняток, а текст конструктора пояснює причину користувачу.
        // 1e100 — науковий запис числа 10 у степені 100. Верхня межа навмисно нижча за максимум double, щоб
        // подальші формули мали запас; вона не змінює тип і не означає округлення значення.
        if (!Double.isFinite(a) || !Double.isFinite(b) || a <= 0 || b <= 0 || a > 1e100 || b > 1e100) throw new IllegalArgumentException("Півосі мають бути в (0; 1e100]."); // Перевіряємо допустимі геометричні параметри.
        // this — поточний об’єкт, аналог self у Python, але його не пишуть у списку параметрів. Ліворуч this.ім’я
        // — поле об’єкта, праворуч однойменне ім’я без this — переданий параметр; тому значення зберігається після
        // завершення конструктора.
        this.a = a; // Зберігаємо масштаб x.
        this.b = b; // Зберігаємо масштаб y.
    }
    public double getA() { return a; } // Getter потрібен також для сортування в лабораторній 5.
    public double getB() { return b; } // Другий параметр використовується як додаткова ознака порядку.
    // abstract означає, що тут задані лише назва, параметри й тип результату методу. Тіла немає: конкретний
    // підклас мусить надати його, приблизно як метод з @abstractmethod у Python.
    public abstract double value(double x); // Кожен підклас зобов'язаний надати власну формулу.
    public abstract void print(double x); // Кожен підклас реалізує спосіб виведення значення.
    // @Override просить компілятор перевірити, що метод справді замінює успадкований метод або реалізує метод
    // інтерфейсу. Якщо помилитися в назві чи параметрах, Java повідомить про це ще до запуску.
    @Override public abstract String toString(); // Вимагаємо змістовного текстового опису підкласу.
    @Override public abstract boolean equals(Object other); // Підкласи явно визначають рівність параметрів.
    // hashCode потрібен хеш-колекціям, приблизно як __hash__ у Python. Рівні за equals об’єкти обов’язково повинні
    // мати однаковий хеш; однаковий хеш сам по собі НЕ доводить рівність. Тут беремо ті самі значущі поля, що й у
    // equals.
    @Override public int hashCode() { return Objects.hash(getClass(), a, b); } // Різні типи та параметри можуть мати різні хеші; рівні об'єкти мають однакові.
}
