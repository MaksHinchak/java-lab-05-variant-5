// class описує тип об’єктів; new створює конкретний об’єкт і викликає його конструктор. public робить клас
// доступним ззовні; final у заголовку класу, якщо він є, забороняє створювати підкласи, але сам по собі не робить
// поля незмінними.
// extends задає єдиний батьківський клас. Виклик методу через змінну базового типу все одно обирає реалізацію
// фактичного об’єкта — так працює поліморфізм, знайомий і з Python.
// implements означає обіцянку виконати контракт інтерфейсу. Comparable<T> вимагає compareTo для природного
// порядку; Comparator<T> — окремий compare для зовнішнього правила сортування; FunctionLike — value і print для
// кривої.
public final class Hyperbola extends Function implements Comparable<Hyperbola> { // Конкретна крива та природний порядок для колекцій.
    // super(...) викликає конструктор батьківського класу для цього самого об’єкта, приблизно як
    // super().__init__(...) у Python. У цих проєктах із рівнем Java 17 цей виклик стоїть першим у конструкторі:
    // спочатку готуємо батьківську частину, потім власні поля.
    public Hyperbola(double a, double b) { super(a, b); } // Передаємо перевірку півосей базовому конструктору.
    // @Override просить компілятор перевірити, що метод справді замінює успадкований метод або реалізує метод
    // інтерфейсу. Якщо помилитися в назві чи параметрах, Java повідомить про це ще до запуску.
    @Override public double value(double x) { // Для однозначності обираємо верхню гілку y >= 0 рівняння x^2/a^2 - y^2/b^2 = 1.
        // Double.isFinite(...) повертає true лише для звичайного скінченного числа; ! заперечує результат. double
        // може містити NaN («не число») і ±Infinity, тому успішний parseDouble ще не гарантує придатність числа
        // для формули. У Python аналог — math.isfinite(x); ця перевірка не перевіряє точність округлення.
        // throw — аналог raise у Python: негайно припиняємо звичайний хід методу й передаємо об’єкт помилки
        // найближчому відповідному catch. new створює виняток, а текст конструктора пояснює причину користувачу.
        if (!Double.isFinite(x) || Math.abs(x) < a) throw new IllegalArgumentException("x поза областю визначення Hyperbola."); // Не допускаємо від'ємного підкореневого виразу.
        // Під коренем (|x|/a-1)(|x|/a+1), тобто (x/a)²-1. Розклад різниці квадратів зручніший біля |x|=a; sqrt
        // бере невід’ємний корінь, тому метод повертає лише верхню гілку гіперболи.
        double result = b * Math.sqrt((Math.abs(x) / a - 1) * (Math.abs(x) / a + 1)); // Виражаємо додатне y через задане x.
        if (!Double.isFinite(result)) throw new ArithmeticException("Переповнення обчислення функції."); // Повідомляємо про вихід за можливості double.
        return result; // Повертаємо значення верхньої гілки.
    }
    @Override public void print(double x) { System.out.println(this + "; x=" + x + "; y=" + value(x)); } // Друкуємо параметри, аргумент і результат.
    @Override public String toString() { return "Hyperbola(a=" + a + ", b=" + b + ")"; } // Повертаємо опис саме цього типу кривої.
    // instanceof одночасно перевіряє фактичний тип і дає змінній праворуч посилання потрібного типу. Це поєднання
    // Python isinstance(...) та присвоєння; для null перевірка дасть false. && не виконує праву частину, якщо тип
    // не підійшов, тому доступ до полів безпечний.
    // Double.compare(a, b) дає від’ємне число, 0 або додатне число залежно від порядку a і b. Для сортування
    // важливий знак; це безпечніше за (int)(a-b), бо невелика різниця не загубиться після відкидання дробової
    // частини.
    @Override public boolean equals(Object other) { return other instanceof Hyperbola f && Double.compare(a, f.a) == 0 && Double.compare(b, f.b) == 0; } // Рівність вимагає однакового типу та двох параметрів.
    @Override public int compareTo(Hyperbola other) { // Природний порядок спочатку за a, потім за b.
        int first = Double.compare(a, other.a); // Порівнюємо головну ознаку сортування.
        // Умова ? значення_якщо_так : значення_якщо_ні — короткий вибір одного з двох значень, аналог a if
        // condition else b у Python. Обчислюється лише вибрана частина, тому інший конструктор чи виклик тут не
        // виконується.
        return first != 0 ? first : Double.compare(b, other.b); // При однаковому a використовуємо b.
    }
}
